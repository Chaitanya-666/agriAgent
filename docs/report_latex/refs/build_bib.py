"""Build references_crossref.bib from the DOIs in dois.tsv, using Crossref metadata only.

Every journal / proceedings entry in the report bibliography comes from this script, so no
author, volume, issue, page or DOI is typed by hand (docs/paper/references.bib once held
fabricated entries). Hand-written entries (datasets, web documentation, arXiv) live in
references_manual.bib.

    python3 -I docs/report_latex/refs/build_bib.py            # writes references_crossref.bib
"""

import json
import pathlib
import time
import urllib.request

HERE = pathlib.Path(__file__).resolve().parent
MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]
# Crossref sometimes lists a chapter under its series; name the conference instead.
CONTAINER_OVERRIDE = {
    "10.1007/978-3-031-72970-6_3": "Proc. European Conference on Computer Vision (ECCV 2024), Lecture Notes in Computer Science",
}
# Crossref splits a few names wrongly; the publisher's page is the reference for these.
AUTHOR_FIX = {
    "10.1016/j.compag.2018.12.048": "Partel, Victor and Kakarla, Sri Charan and Ampatzidis, Yiannis",
}
TEX = {"&": r"\&", "%": r"\%", "_": r"\_", "#": r"\#"}


def tex(text: str) -> str:
    text = text.replace("‐", "-").replace("‑", "-").replace("–", "--").replace("—", "---")
    text = " ".join(text.split())
    return "".join(TEX.get(ch, ch) for ch in text)


def fetch(doi: str) -> dict:
    cache = HERE / "crossref_cache" / (doi.replace("/", "_") + ".json")
    if cache.exists():
        return json.loads(cache.read_text())
    req = urllib.request.Request(f"https://api.crossref.org/works/{doi}", headers={"User-Agent": "report-bib/1.0"})
    msg = json.load(urllib.request.urlopen(req, timeout=30))["message"]
    cache.parent.mkdir(exist_ok=True)
    cache.write_text(json.dumps(msg, indent=1))
    time.sleep(0.5)
    return msg


def entry(key: str, doi: str) -> str:
    m = fetch(doi)
    authors = " and ".join(
        f"{tex(a['family'])}, {tex(a.get('given', ''))}".rstrip(", ") if "family" in a else "{" + tex(a["name"]) + "}"
        for a in m.get("author", [])
    )
    authors = AUTHOR_FIX.get(doi, authors)
    date = (m.get("published-print") or m.get("journal-issue", {}).get("published-print") or m.get("published-online") or m["issued"])["date-parts"][0]
    container = CONTAINER_OVERRIDE.get(doi, tex(m.get("container-title", [""])[-1] if m["type"] == "book-chapter" else m.get("container-title", [""])[0]))
    is_article = m["type"] == "journal-article"
    fields = {"author": authors, "title": "{" + tex(m["title"][0]) + "}"}
    fields["journal" if is_article else "booktitle"] = container
    if m.get("volume"):
        fields["volume"] = m["volume"]
    if m.get("issue"):
        fields["number"] = m["issue"]
    page = m.get("page")
    notes = []
    if page and "-" in page:
        fields["pages"] = page.replace("-", "--")
    elif m.get("article-number") or page:
        notes.append(f"Art. no. {m.get('article-number') or page}")  # IEEE style for e-journals
    if len(date) > 1:
        fields["month"] = MONTHS[date[1] - 1]
    fields["year"] = str(date[0])
    notes.append(r"doi: \href{https://doi.org/" + doi + "}{" + tex(doi) + "}")
    fields["note"] = ", ".join(notes)
    body = ",\n".join(f"  {k} = {{{v}}}" if k not in ("month",) else f"  {k} = {v}" for k, v in fields.items())
    return f"@{'article' if is_article else 'inproceedings'}{{{key},\n{body}\n}}\n"


def main() -> None:
    rows = [line.split("\t") for line in (HERE / "dois.tsv").read_text().splitlines() if line and not line.startswith("#")]
    out = ["% GENERATED by build_bib.py from Crossref. Do not edit by hand; edit dois.tsv and rerun.\n"]
    out += [entry(key.strip(), doi.strip()) for key, doi in rows]
    (HERE.parent / "references_crossref.bib").write_text("\n".join(out))
    print(f"{len(rows)} entries written")


if __name__ == "__main__":
    main()
